from core import beat_pos, beat_time


def snap(t, div=2):
    b = beat_pos(t)
    return beat_time(round(b * div) / div)


def L(text, times, style='verse', who='val', pos='b', echo=()):
    w = text.split()
    assert len(w) == len(times), (text, len(w), len(times))
    return dict(text=text, words=w, times=[snap(x) for x in times], raw=list(times), style=style, who=who, pos=pos, echo=[snap(x) for x in echo])


