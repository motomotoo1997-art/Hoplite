def vowel(w):
    for ch in w.lower():
        if ch in VOW: return VOW[ch]
    return None


WORDS = {'val': [], 'shk': []}
for ln in LINES:
    if ln['who'] not in WORDS: continue
    for w, x in zip(ln['words'], ln['times']):
        v = vowel(w)
        if v: WORDS[ln['who']].append((x, v))
    for x in ln['echo']: WORDS[ln['who']].append((x, 'a'))
for k in WORDS: WORDS[k].sort()
